static int sensor_hw_reset(void)
{
	int ret = 0;
	static hal_gpio_adapter_t gpio_rstp;
	gpio_rstp.pin_name = PIN_E0;
	hal_gpio_init(&gpio_rstp, PIN_E0);
	hal_gpio_set_dir(&gpio_rstp, GPIO_OUT);
	hal_gpio_write(&gpio_rstp, 0);
	hal_delay_us(1000);
	hal_gpio_write(&gpio_rstp, 1);
	return ret;
}

int video_boot_init_sensor_config(void)
{
	//return 0;

	int ret = 0;
	int retry = 5;
	int id = 0xFFFF;
	uint16_t data;

	sensor_hw_reset();
	do {
		id = 0xFFFF;
		if (retry != 5) {
			dbg_printf("%s/%d retry %d\r\n", __FUNCTION__, __LINE__, retry);
			hal_delay_us(10000 * (5 - retry));
		}
		retry = retry - 1;
		ret = hal_voe_i2c_read(0x03f0, &data);
		if (ret != 0) {
			continue;
		}
		id = data << 8;
		ret = hal_voe_i2c_read(0x03f1, &data);
		if (ret != 0) {
			continue;
		}
		id |= data;
		break;
	} while (retry >= 0);

	if (id == 0x4693) {
		for (int i = 0; i < (sizeof(g_gc4693_i2c_init_regs_binning) / sizeof(g_gc4693_i2c_init_regs_binning[0])); i++) {
			hal_voe_i2c_write(g_gc4693_i2c_init_regs_binning[i].addr, g_gc4693_i2c_init_regs_binning[i].data);
		}
	} else {
		return -1;
	}

	return ret;
}

