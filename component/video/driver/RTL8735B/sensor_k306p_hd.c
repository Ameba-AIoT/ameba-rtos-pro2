int sensor_power_on_sequence(int on)
{
	int ret = 0;
	static hal_gpio_adapter_t gpio_rstp;
	gpio_rstp.pin_name = PIN_E0;
	if (on) {
		//hclk_set_rate(0);
		//hal_gpio_deinit(&gpio_rstp);
		hal_gpio_init(&gpio_rstp, PIN_E0);
		hal_gpio_set_dir(&gpio_rstp, GPIO_OUT);
		hal_gpio_write(&gpio_rstp, 0);
		hal_delay_us(1000);
		hal_gpio_write(&gpio_rstp, 1);
	}
	return ret;
}

int video_boot_init_sensor_config(void)
{
	//return 0;

	int ret = 0;
	int retry = 5;
	int id = 0xFFFF;
	uint16_t data;

	sensor_power_on_sequence(1);
	do {
		id = 0xFFFF;
		if (retry != 5) {
			dbg_printf("%s/%d retry %d\r\n", __FUNCTION__, __LINE__, retry);
			hal_delay_us(10000 * (5 - retry));
		}
		retry = retry - 1;
		ret = hal_voe_i2c_read(0x0A, &data);
		if (ret != 0) {
			continue;
		}
		id = data << 8;
		ret = hal_voe_i2c_read(0x0B, &data);
		if (ret != 0) {
			continue;
		}
		id |= data;
		break;
	} while (retry >= 0);

	if (id == 0x0860) {
		for (int i = 0; i < (sizeof(g_k306p_bin_i2c_init_regs_asic) / sizeof(g_k306p_bin_i2c_init_regs_asic[0])); i++) {
			hal_voe_i2c_write(g_k306p_bin_i2c_init_regs_asic[i].addr, g_k306p_bin_i2c_init_regs_asic[i].data);
		}
	} else {
		sensor_power_on_sequence(0);
		return -22;
	}

	return ret;
}

