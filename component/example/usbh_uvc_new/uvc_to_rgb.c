/* Safe sized-realloc: never calls platform realloc() */
static void *safe_realloc(void *p, size_t old_sz, size_t new_sz)
{
	void *n;
	if (!p) {
		return rtw_malloc(new_sz);
	}
	if (!new_sz) {
		rtw_free(p);
		return NULL;
	}
	n = rtw_malloc(new_sz);
	if (n) {
		memcpy(n, p, old_sz < new_sz ? old_sz : new_sz);
	}
	rtw_free(p);
	return n;
}

