/* Walk JPEG segments. Returns 1 if a DHT (FFC4) segment exists before SOS.
 * *sos_off is set to the byte offset of the SOS marker (FFDA), or -1. */
static int jpeg_scan_markers(const uint8_t *b, int len, int *sos_off)
{
	int i = 2;              /* skip SOI (FFD8) */
	int has_dht = 0;
	*sos_off = -1;
	if (len < 4 || b[0] != 0xFF || b[1] != 0xD8) {
		return -1;    /* not a JPEG */
	}
	while (i + 4 <= len) {
		if (b[i] != 0xFF) {
			i++;
			continue;
		}
		uint8_t m = b[i + 1];
		if (m == 0xFF) {
			i++;    /* fill byte */
			continue;
		}
		if (m == 0x01 || (m >= 0xD0 && m <= 0xD9)) {
			i += 2;    /* standalone */
			continue;
		}
		if (m == 0xDA) {
			*sos_off = i;    /* SOS */
			break;
		}
		if (m == 0xC4) {
			has_dht = 1;    /* DHT */
		}
		{
			int seglen = (b[i + 2] << 8) | b[i + 3];
			if (seglen < 2) {
				break;    /* malformed */
			}
			i += 2 + seglen;
		}
	}
	return has_dht;
}

uint8_t *uvc_yuy2_to_rgb(uint8_t *s, int w, int h, uint8_t *d, int f)
{
	int x, y;
	uint8_t *sr, *dr;
	int ss = w * 2, ds = w * 3;
	uint8_t y0, y1, u, v, r, g, b;
	if (!s || w <= 0 || h <= 0) {
		return NULL;
	}
	if (!d) {
		d = rtw_malloc(h * ds);
		if (!d) {
			return NULL;
		}
	}
	for (y = 0; y < h; y++) {
		sr = s + y * ss;
		dr = d + y * ds;
		for (x = 0; x < w; x += 2) {
			y0 = sr[0];
			u = sr[1];
			y1 = sr[2];
			v = sr[3];
			CONVERT_YUV_TO_RGB(y0, u, v, r, g, b);
			if (f == 1) {
				dr[0] = b;
				dr[1] = g;
				dr[2] = r;
			} else {
				dr[0] = r;
				dr[1] = g;
				dr[2] = b;
			}
			CONVERT_YUV_TO_RGB(y1, u, v, r, g, b);
			if (f == 1) {
				dr[3] = b;
				dr[4] = g;
				dr[5] = r;
			} else {
				dr[3] = r;
				dr[4] = g;
				dr[5] = b;
			}
			sr += 4;
			dr += 6;
		}
	}
	return d;
}

uint8_t *uvc_jpeg_to_rgb(uint8_t *src, int len, int *w, int *h, uint8_t *dst, int f)
{
	int x, y, c;
	stbi_uc *img;
	int sos_off = -1;
	int has_dht;
	uint8_t *decode_buf = src;
	int decode_len = len;
	uint8_t *aug = NULL;
	if (!src || len <= 0) {
		return NULL;
	}

	has_dht = jpeg_scan_markers(src, len, &sos_off);
	printf("\n[JPEG]scan: dht=%d sos_off=%d m0=%02X%02X\n",
		   has_dht, sos_off, src[0], src[1]);

	/* MJPEG frames often omit DHT: inject the standard Huffman tables
	 * right before the SOS marker so stb_image can decode them. */
	if (has_dht == 0 && sos_off > 0) {
		int newlen = len + (int)sizeof(mjpeg_dht);
		aug = rtw_malloc(newlen);
		if (aug) {
			memcpy(aug, src, sos_off);
			memcpy(aug + sos_off, mjpeg_dht, sizeof(mjpeg_dht));
			memcpy(aug + sos_off + sizeof(mjpeg_dht), src + sos_off, len - sos_off);
			decode_buf = aug;
			decode_len = newlen;
			printf("\n[JPEG]injected standard DHT (%u bytes)\n", (unsigned)sizeof(mjpeg_dht));
		}
	}

	img = stbi_load_from_memory(decode_buf, decode_len, &x, &y, &c, 3);
	if (aug) {
		rtw_free(aug);
	}
	if (!img) {
		printf("\n[JPEG]%s\n", stbi_failure_reason());
		return NULL;
	}
	if (w) {
		*w = x;
	}
	if (h) {
		*h = y;
	}
	if (f == 1) {
		stbi_uc *p = img, t;
		for (int i = x * y; i > 0; i--) {
			t = p[0];
			p[0] = p[2];
			p[2] = t;
			p += 3;
		}
	}
	if (dst) {
		memcpy(dst, img, x * y * 3);
		stbi_image_free(img);
		return dst;
	}
	return (uint8_t *)img;
}
void uvc_rgb_free(uint8_t *b)
{
	stbi_image_free(b);
}
